const REGION_BY_CODE = new Map<string, RegionDefinition>(
  REGION_DICTIONARY.map((entry) => [entry.code.toUpperCase(), entry]),
);

export function listRegionDefinitions(): readonly RegionDefinition[] {
  return REGION_DICTIONARY;
}

export function getRegionDefinition(code: string): RegionDefinition | undefined {
  return REGION_BY_CODE.get(code.trim().toUpperCase());
}

/** Looks up a region by ISO code, flag emoji, Chinese name, or English name. */
export function findRegionByQuery(query: string): RegionDefinition | undefined {
  const normalized = query.trim();
  if (!normalized) return undefined;
  const byCode = REGION_BY_CODE.get(normalized.toUpperCase());
  if (byCode) return byCode;
  const lower = normalized.toLowerCase();
  return REGION_DICTIONARY.find(
    (entry) =>
      entry.flag === normalized ||
      entry.nameZh === normalized ||
      entry.nameEn.toLowerCase() === lower ||
      entry.zhTerms.includes(normalized) ||
      entry.enTerms.some((term) => term.toLowerCase() === lower),
  );
}
