/**
 * Built-in region dictionary for node name matching and region-group regex
 * compilation (design §10.11).
 *
 * Authored independently for Private Rules (ISO 3166-1 alpha-2 codes, standard
 * country/city names, IATA airport codes, and curated false-positive exclusions).
 */

export type RegionDefinition = {
  /** ISO 3166-1 alpha-2 region code (uppercase). */
  code: string;
  /** Primary Simplified Chinese display name. */
  nameZh: string;
  /** Primary English display name. */
  nameEn: string;
  /** Regional indicator flag emoji. */
  flag: string;
  /** Unambiguous multi-character Chinese names, aliases, and major cities. */
  zhTerms: readonly string[];
  /**
   * Single-character Chinese shorthands (e.g. `日`, `港`, `台`, `新`) that
   * require exclusion guards to prevent false positives such as `尼日利亚` or `新西兰`.
   */
  shortZhTerms?: readonly string[];
  /** Unambiguous English country / city / ISP terms (matched case-insensitively). */
  enTerms: readonly string[];
  /** Short ISO / IATA / airport codes matched with ASCII letter boundaries (case-insensitive). */
  codes: readonly string[];
  /**
   * Short ISO codes that collide with common English words (e.g. `MY` vs "My")
   * and should only match when written in UPPERCASE.
   */
  strictCaseCodes?: readonly string[];
  /**
   * Words containing a shorthand or ambiguous substring that must NOT match
   * this region (e.g. `尼日利亚` for `JP`, `新西兰` for `SG`, `澳门` for `AU`).
   */
  excludes: readonly string[];
};

