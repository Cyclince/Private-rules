/**
 * Build-time Traditional Chinese dictionary generator (design §13.5).
 * Uses `opencc-js` (`cn -> twp`) + manual `zh-TW.overrides.ts` to emit
 * `src/web/i18n/zh-TW.ts` so the runtime web bundle contains zero OpenCC code.
 */
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as OpenCC from 'opencc-js';
import { zhCN, type MessageKey, type Messages } from '../src/web/i18n/zh-CN';
import { ZH_TW_KEY_OVERRIDES, ZH_TW_TERM_OVERRIDES } from '../src/web/i18n/zh-TW.overrides';

const converter = OpenCC.Converter({ from: 'cn', to: 'twp' });

export function convertToZhTW(source: Record<string, string>): Messages {
  const result = {} as Record<MessageKey, string>;
  for (const key of Object.keys(source) as MessageKey[]) {
    const manual = ZH_TW_KEY_OVERRIDES[key];
    if (manual !== undefined) {
      result[key] = manual;
      continue;
    }
    let converted = converter(source[key]);
    for (const [from, to] of ZH_TW_TERM_OVERRIDES) {
      converted = converted.split(from).join(to);
    }
    result[key] = converted;
  }
  return result;
}

function quoteSingle(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

export function renderZhTwModule(messages: Messages): string {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-zh-tw.ts — do not edit manually.',
    '// Edit src/web/i18n/zh-CN.ts or src/web/i18n/zh-TW.overrides.ts and re-run `pnpm i18n:generate`.',
    "import type { Messages } from './zh-CN';",
    '',
    'export const zhTW: Messages = {',
  ];
  for (const [key, value] of Object.entries(messages)) {
    lines.push(`  ${quoteSingle(key)}: ${quoteSingle(value)},`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

const isEntrypoint = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isEntrypoint) {
  const outPath = resolve(process.cwd(), 'src/web/i18n/zh-TW.ts');
  const messages = convertToZhTW(zhCN);
  await writeFile(outPath, renderZhTwModule(messages), 'utf8');
  console.info(`[i18n] generated ${Object.keys(messages).length} Traditional Chinese entries in ${outPath}`);
}
